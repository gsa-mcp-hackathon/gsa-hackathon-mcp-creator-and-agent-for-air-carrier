"""Re-derive the delegation results from the logged runs, with 95% intervals.

    python3 eval/delegation/analyze.py            # prints the table
    python3 eval/delegation/analyze.py --write    # also rewrites RESULTS.md

runs.csv is an export of users.xiaobing_shang1_civ.aircarrier_delegation_eval_runs
(224 rows, 2026-11-18 and 2026-11-19), without the trace and answer columns.
The headline run is rpt-2317840a: both models, three repeats with all 29 tools
offered at once, and one no-tool baseline, on 9 development and 5 held-out
questions. Intervals are Wilson score intervals, which stay inside [0, 1] and
behave at 0% and 100%, where the normal approximation does not.
"""

from __future__ import annotations

import csv
import math
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADLINE = "rpt-2317840a"
Z = 1.959963984540054


def wilson(k: int, n: int) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    denom = 1 + Z**2 / n
    centre = (p + Z**2 / (2 * n)) / denom
    half = Z * math.sqrt(p * (1 - p) / n + Z**2 / (4 * n**2)) / denom
    return (max(0.0, centre - half), min(1.0, centre + half))


def fmt(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {100 * k / n:.1f}% (95% CI {100 * lo:.1f} to {100 * hi:.1f})"


def load() -> list[dict]:
    with open(HERE / "runs.csv", newline="", encoding="utf-8") as f:
        return [r for r in csv.DictReader(f) if r["run_id"]]


def tools(mode: str) -> bool:
    return mode.startswith("tools_rep")


def not_f1(qid: str) -> bool:
    return qid != "F1 FY10 total"


def tally(rows, **match) -> tuple[int, int]:
    sel = [
        r
        for r in rows
        if all(r[k] == v or (callable(v) and v(r[k])) for k, v in match.items())
    ]
    return sum(int(r["passed"]) for r in sel), len(sel)


def report() -> str:
    rows = load()
    run = [r for r in rows if r["run_id"] == HEADLINE]
    out = [
        "# Delegation results, re-derived from the logged runs",
        "",
        (
            f"Generated by `eval/delegation/analyze.py` from `runs.csv` ({len(rows)} rows). "
            f"Headline run `{HEADLINE}`, tool catalog `{run[0]['tool_catalog_sha']}`."
        ),
        "Two models (Claude Sonnet 4.5, GPT-5 mini) receive all 29 One Hub tools at once.",
        (
            'The five held-out ("fresh") questions were written after the development set. '
            "One of them, F1, failed in the first run and led to a fix (a fiscal-year filter "
            "on the obligations tool), so F1 is no longer untouched; the strict held-out row "
            "leaves it out. Intervals are 95% Wilson score intervals."
        ),
        "",
        "| Split | With the 29 tools (3 repeats) | No tools (baseline) |",
        "|---|---|---|",
    ]
    for label, match in (
        (
            "Strict held-out (4 questions, F1 excluded)",
            {"question_set": "fresh", "qid": not_f1},
        ),
        ("Held-out (5 questions)", {"question_set": "fresh"}),
        ("Development (9 questions)", {"question_set": "dev"}),
        ("All 14 questions", {}),
    ):
        k, n = tally(run, mode=tools, **match)
        kb, nb = tally(run, mode="no_tools", **match)
        out.append(f"| {label} | {fmt(k, n)} | {fmt(kb, nb)} |")
    out += [
        "",
        "By model, held-out only:",
        "",
        "| Model | With tools | No tools |",
        "|---|---|---|",
    ]
    for model in sorted({r["model"] for r in run}):
        k, n = tally(run, model=model, question_set="fresh", mode=tools)
        kb, nb = tally(run, model=model, question_set="fresh", mode="no_tools")
        out.append(f"| {model} | {fmt(k, n)} | {fmt(kb, nb)} |")

    # pass^3: a question counts only if all three repeats pass, per model
    per = defaultdict(list)
    for r in run:
        if tools(r["mode"]):
            per[(r["model"], r["question_set"], r["qid"])].append(int(r["passed"]))
    p3 = defaultdict(lambda: [0, 0])
    for (model, qs, _), v in per.items():
        p3[qs][0] += all(v)
        p3[qs][1] += 1
    out += [
        "",
        "Consistency (pass^3: a question passes only if all three repeats pass, per model):",
        "",
    ]
    for qs, label in (("fresh", "held-out"), ("dev", "development")):
        out.append(f"- {label}: {p3[qs][0]} of {p3[qs][1]} question-model pairs")

    misses = sorted(
        {(r["model"], r["qid"]) for r in run if tools(r["mode"]) and r["passed"] == "0"}
    )
    out += [
        "",
        "Every miss with tools: " + "; ".join(f"{q} ({m})" for m, q in misses) + ".",
    ]

    # server instructions in the prompt, run fcb4cba76cf4
    k, n = tally(rows, run_id="fcb4cba76cf4", mode="instr")
    out += [
        "",
        f"With each server's instructions in the system prompt (run `fcb4cba76cf4`): {fmt(k, n)}.",
    ]

    # the fix the first run exposed
    before = tally(rows, run_id="01eb115e567a", qid="F1 FY10 total")
    after = tally(rows, run_id="fcb4cba76cf4", qid="F1 FY10 total")
    out += [
        (
            f"F1 FY10 total before the fiscal-year filter (run `01eb115e567a`): "
            f"{before[0]}/{before[1]}; after (run `fcb4cba76cf4`): {after[0]}/{after[1]}."
        ),
        "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    text = report()
    print(text)
    if "--write" in sys.argv:
        (HERE / "RESULTS.md").write_text(text + "\n", encoding="utf-8")
