"""Upgrade a generated project to this Creator release, keeping the owner's edits.

A generated project carries the specification it came from and the hash of
every file as generated (.mcp-creator/, see generators/provenance.py). This
regenerates the project from that specification and compares three versions
of each file: as generated then (lock.json), as it is now (disk), and as this
Creator generates it (new).

    unchanged   the template did not change; the file is left as it is
    update      the template changed and nobody edited the file: replaced
    add         a file this release generates that the project lacks: written
    owned       listed in owned.txt: left as the owner has it, whatever changed
    conflict    edited, not declared in owned.txt, and the template changed
    retired     generated before, not by this release: left in place, reported

A conflict stops the upgrade before anything is written. Declare the file in
owned.txt to keep your version, or restore the generated one, then run again.

    mcp-a-creator-upgrade path/to/project            # show the plan
    mcp-a-creator-upgrade path/to/project --write    # apply it
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from dataclasses import dataclass, field
from pathlib import Path

from mcp_server_creator import __version__
from mcp_server_creator.generators import generate_full_project
from mcp_server_creator.generators.provenance import (
    LOCK_PATH,
    OWNED_PATH,
    SPEC_PATH,
    UNLOCKED,
)
from mcp_server_creator.models import ServerSpec

ACTIONS = ("unchanged", "update", "add", "owned", "conflict", "retired")


class NotACreatorProject(Exception):
    """The folder has no readable .mcp-creator/ spec and lock."""


@dataclass
class UpgradePlan:
    project: Path
    from_version: str
    to_version: str
    actions: dict[str, list[str]] = field(
        default_factory=lambda: {a: [] for a in ACTIONS}
    )
    new_files: dict[str, str] = field(default_factory=dict)

    @property
    def can_apply(self) -> bool:
        return not self.actions["conflict"]

    @property
    def writes(self) -> list[str]:
        return sorted(self.actions["update"] + self.actions["add"])

    def summary(self) -> str:
        counts = ", ".join(f"{len(self.actions[a])} {a}" for a in ACTIONS)
        lines = [
            f"{self.project.name}: generated by MCP A Creator {self.from_version}; "
            f"upgrade to {self.to_version}: {counts}."
        ]
        for action in ("update", "add", "owned", "conflict", "retired"):
            for path in self.actions[action]:
                lines.append(f"  {action:9} {path}")
        if self.actions["conflict"]:
            lines.append(
                "Nothing written. For each conflict, add the path to "
                f"{OWNED_PATH} to keep your version, or restore the generated "
                "file, then run again."
            )
        return "\n".join(lines)


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _owned(project: Path) -> set[str]:
    f = project / OWNED_PATH
    if not f.exists():
        return set()
    out = set()
    for line in f.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            out.add(line)
    return out


def plan_upgrade(project: Path) -> UpgradePlan:
    """Compare the project with what this Creator generates from its spec."""
    project = Path(project).resolve()
    try:
        lock = json.loads((project / LOCK_PATH).read_text(encoding="utf-8"))
        spec = ServerSpec.model_validate_json(
            (project / SPEC_PATH).read_text(encoding="utf-8")
        )
    except FileNotFoundError as exc:
        raise NotACreatorProject(
            f"{project} has no {LOCK_PATH} or {SPEC_PATH}; it was not generated "
            "by MCP A Creator 1.0 or later, or the folder was moved without them."
        ) from exc
    except ValueError as exc:
        raise NotACreatorProject(
            f"{SPEC_PATH} does not load in MCP A Creator {__version__}: {exc}"
        ) from exc

    old = lock.get("files", {})
    # Regenerate the same parts the project was generated with.
    manifest = generate_full_project(
        spec,
        include_evaluation=any(p.startswith("eval/") for p in old),
        include_deployment="app.yaml" in old,
    )
    new = {f.path: f.content for f in manifest.files}
    owned = _owned(project)
    plan = UpgradePlan(
        project, lock.get("creator_version", "?"), __version__, new_files=new
    )

    for path in sorted((set(old) | set(new)) - UNLOCKED):
        disk = project / path
        on_disk = disk.read_bytes() if disk.is_file() else None
        if path not in new:
            plan.actions["retired"].append(path)
            continue
        new_hash = _sha(new[path].encode("utf-8"))
        if path in owned:
            # The owner's file, even if the template changed or it is gone.
            plan.actions["owned"].append(path)
        elif on_disk is None:
            plan.actions["add"].append(path)
        elif path not in old:
            # A new template file whose path the owner already uses.
            same = _sha(on_disk) == new_hash
            plan.actions["unchanged" if same else "conflict"].append(path)
        elif _sha(on_disk) == new_hash:
            plan.actions["unchanged"].append(path)
        elif _sha(on_disk) == old[path]:
            plan.actions["update"].append(path)
        elif new_hash == old[path]:
            # Edited by hand but the template did not move: drift check's job.
            plan.actions["unchanged"].append(path)
        else:
            plan.actions["conflict"].append(path)
    return plan


def apply_upgrade(plan: UpgradePlan) -> list[str]:
    """Write updates, additions and the new lock. Refuses when there are conflicts.

    The new lock records this release's hashes, so an owned file that differs
    stays declared and check_drift.py keeps passing.
    """
    if not plan.can_apply:
        raise ValueError("The plan has conflicts; nothing was written.")
    root = plan.project
    for path in plan.writes:
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(plan.new_files[path], encoding="utf-8", newline="\n")
    (root / LOCK_PATH).write_text(
        plan.new_files[LOCK_PATH], encoding="utf-8", newline="\n"
    )
    return plan.writes + [LOCK_PATH]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="mcp-a-creator-upgrade",
        description=(
            "Regenerate a project made by MCP A Creator with this release, "
            "keeping every file listed in .mcp-creator/owned.txt. Shows the "
            "plan unless --write is given."
        ),
    )
    parser.add_argument("project", type=Path, help="the generated project's folder")
    parser.add_argument("--write", action="store_true", help="apply the plan")
    parser.add_argument(
        "--version", action="version", version=f"mcp-a-creator {__version__}"
    )
    args = parser.parse_args(argv)
    try:
        plan = plan_upgrade(args.project)
    except NotACreatorProject as exc:
        print(exc, file=sys.stderr)
        return 2
    print(plan.summary())
    if not plan.can_apply:
        return 1
    if args.write:
        written = apply_upgrade(plan)
        print(f"Wrote {len(written)} files.")
    elif plan.writes:
        print("Run again with --write to apply.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
