"""Provenance: every generated project says what made it, and notices edits.

A generated server outlives its first generation. Someone renames a tool or
fixes a query by hand, and a later Creator release improves the templates.
Without a record of what was generated, the two cannot be reconciled: the
hand edits are overwritten, or the project never gets the improvements (the
ops server in this repository is the example: edited after generation, it is
now outside the Creator's reach).

So every project carries, in .mcp-creator/:

  spec.json       the specification it was generated from
  lock.json       the Creator version, the spec's SHA-256 and every file's SHA-256
  owned.txt       files the owner has taken over by hand (one path per line)
  check_drift.py  run in CI: fails when a generated file was edited but is
                  not listed in owned.txt, so every hand edit is declared

The lock carries no timestamp, so generating twice is still byte-identical.
"""

from __future__ import annotations

import hashlib
import json

from mcp_server_creator import __version__
from mcp_server_creator.models import FileManifest, ServerSpec

LOCK_DIR = ".mcp-creator"
SPEC_PATH = f"{LOCK_DIR}/spec.json"
LOCK_PATH = f"{LOCK_DIR}/lock.json"
OWNED_PATH = f"{LOCK_DIR}/owned.txt"
DRIFT_PATH = f"{LOCK_DIR}/check_drift.py"
# Not hashed: the lock itself, and the owner's own list.
UNLOCKED = {LOCK_PATH, OWNED_PATH}

OWNED_TXT = """# Files you have taken over by hand, one project-relative path per line.
# A file listed here may differ from what MCP A Creator generated; any other
# generated file that differs fails .mcp-creator/check_drift.py in CI.
# An upgrade with a newer Creator keeps these files as they are.
"""

CHECK_DRIFT = '''"""Fail when a generated file was edited but not declared in owned.txt.

Run from the project root: python .mcp-creator/check_drift.py
Exit 0: every file matches lock.json or is declared. Exit 1: undeclared edits.
"""

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> int:
    lock = json.loads((ROOT / ".mcp-creator/lock.json").read_text(encoding="utf-8"))
    owned_file = ROOT / ".mcp-creator/owned.txt"
    owned = set()
    if owned_file.exists():
        for line in owned_file.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                owned.add(line)
    edited, missing = [], []
    for path, digest in sorted(lock["files"].items()):
        f = ROOT / path
        if not f.exists():
            missing.append(path)
        elif hashlib.sha256(f.read_bytes()).hexdigest() != digest:
            edited.append(path)
    undeclared = [p for p in edited + missing if p not in owned]
    print(f"Generated by MCP A Creator {lock['creator_version']}; "
          f"{len(lock['files'])} files locked, {len(edited)} edited, "
          f"{len(missing)} missing, {len(owned)} declared in owned.txt.")
    for p in undeclared:
        print(f"  undeclared: {p}")
    if undeclared:
        print("Declare each edited file in .mcp-creator/owned.txt, or regenerate it.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def spec_json(spec: ServerSpec) -> str:
    """The specification as stable JSON: sorted keys, two-space indent."""
    return json.dumps(spec.model_dump(mode="json"), indent=2, sort_keys=True) + "\n"


def add_files(manifest: FileManifest, spec: ServerSpec) -> None:
    """Add spec.json, owned.txt and check_drift.py. Call before formatting."""
    manifest.add(
        SPEC_PATH, spec_json(spec), "The specification this project was generated from"
    )
    manifest.add(OWNED_PATH, OWNED_TXT, "Files the owner has taken over by hand")
    manifest.add(DRIFT_PATH, CHECK_DRIFT, "CI check: every hand edit is declared")


def stamp(manifest: FileManifest, spec: ServerSpec) -> None:
    """Add lock.json. Call last, after formatting, so each hash is of the file
    as written."""
    body = spec_json(spec)
    files = {
        f.path: sha256(f.content)
        for f in sorted(manifest.files, key=lambda f: f.path)
        if f.path not in UNLOCKED
    }
    lock = {
        "format": 1,
        "creator": "mcp-a-creator",
        "creator_version": __version__,
        "server_name": spec.server_name,
        "spec_sha256": sha256(body),
        "files": files,
    }
    manifest.add(
        LOCK_PATH,
        json.dumps(lock, indent=2, sort_keys=True) + "\n",
        "Creator version, spec hash and the hash of every generated file",
    )


def read_lock(files: dict[str, str]) -> dict | None:
    """The lock from a project's files (path to text), or None."""
    text = files.get(LOCK_PATH)
    return json.loads(text) if text else None


def owned_paths(files: dict[str, str]) -> set[str]:
    out = set()
    for line in (files.get(OWNED_PATH) or "").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            out.add(line)
    return out
