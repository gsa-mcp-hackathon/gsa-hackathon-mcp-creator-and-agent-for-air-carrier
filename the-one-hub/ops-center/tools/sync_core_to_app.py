#!/usr/bin/env python3
"""Vendor core/ into app/_core/, and the retrieval half of ops/ingest into
app/_ops/, so app/ is a self-contained transfer unit.

The app ships app/ only. Without app/_ops, /api/search answers "Retrieval is
not available in this deployment" (verified on deployment 01f1dbc0, 2026-11-08).

Run before any app build. Idempotent.

Why this exists: Advana FM needs its own GitLab repo with the Dragon pipeline
to deploy the App, and that pipeline gets app/ and nothing else. core/ stays
the single source of the contract, and app/ stays complete on disk.
"""
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "core"
DST = ROOT / "app" / "_core"

KEEP = {"README.md"}

# Read side of retrieval only. The app never builds the index, so extract,
# chunk and the ingest job stay out of the transfer unit.
OPS_FILES = ["ingest/search.py", "ingest/index.py"]
OPS_DST = ROOT / "app" / "_ops"


def sync_ops() -> None:
    shutil.rmtree(OPS_DST, ignore_errors=True)
    (OPS_DST / "ops" / "ingest").mkdir(parents=True)
    (OPS_DST / "ops" / "__init__.py").write_text(
        '"""Vendored subset of ops/. Generated by tools/sync_core_to_app.py. Never edit here."""\n')
    (OPS_DST / "ops" / "ingest" / "__init__.py").write_text("")
    for rel in OPS_FILES:
        shutil.copy2(ROOT / "ops" / rel, OPS_DST / "ops" / rel)
    print(f"synced ops/{{{','.join(OPS_FILES)}}} -> {OPS_DST}")


def main() -> int:
    if not SRC.is_dir():
        print(f"no core/ at {SRC}", file=sys.stderr)
        return 1
    for child in DST.iterdir() if DST.exists() else []:
        if child.name in KEEP:
            continue
        shutil.rmtree(child) if child.is_dir() else child.unlink()
    shutil.copytree(SRC, DST / "core", dirs_exist_ok=True)
    print(f"synced {SRC} -> {DST / 'core'}")
    sync_ops()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
