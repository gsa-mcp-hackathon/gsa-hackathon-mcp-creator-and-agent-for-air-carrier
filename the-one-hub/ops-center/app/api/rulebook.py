"""The /rules page: every code the product uses, each read from where it is defined.

    SI rulebook     si/tasks.RULEBOOK, the text the specialist is given, read
                    in process. EC-01 and EC-02 are sdk.SYSTEM_RULES: the gate
                    and the canvas, not rules a specialist cites.
    Rule register   aircarrier_app_rule_register, read live on every request
                    (harness_sql.rule_catalog). When the warehouse cannot be
                    read, the page shows the snapshot in data/rules.json and
                    says how old it is and why the live read failed.
    Gate routes     seed/gate.yaml, copied into data/rules.json because seed/
                    is not deployed with the app.

Nothing on the page is typed by hand. data/rules.json is generated: edit the
source, then rebuild it on Spark with

    python etl/build_rules.py --root <bundle files dir>
"""
from __future__ import annotations

import json
from collections.abc import Callable

from . import data
from . import harness_sql as H
from .si import sdk, tasks

QueryFn = Callable[[str, dict], list[dict]]

# Display order and labels for rule_register.area. An area missing here still
# shows, after these, under its stored name.
AREAS = {"cost_capture": "Cost capture", "evm": "EVM", "cost_cap": "Cost cap",
         "valuation": "Valuation", "cost_model": "Cost model"}


def si_rules() -> list[dict]:
    """The SI rulebook exactly as the specialist receives it."""
    return [{"code": code, "description": text, "system": code in sdk.SYSTEM_RULES}
            for code, text in tasks.RULEBOOK.items()]


def params_text(params) -> str:
    """A rule's params as one line, e.g. 'cpi_floor: 0.95'. An empty value is
    shown as 'unset', because that is why a blocked_param_unset rule is blocked.
    params arrives as a dict from Spark and as JSON text from the warehouse."""
    if isinstance(params, str):
        params = json.loads(params) if params.strip() else {}
    return ", ".join(f"{k}: {v if v not in (None, '') else 'unset'}"
                     for k, v in (params or {}).items())


def _rule(row: dict) -> dict:
    return {"code": row["rule_id"], "description": row.get("statement_text"),
            "params": params_text(row.get("params")), "status": row.get("status"),
            "blocked_reason": row.get("blocked_reason"),
            "required_action": row.get("required_action"),
            "version": int(row["version"]),
            "version_count": int(row.get("version_count") or 1),
            "current_version": (int(row["current_version"])
                                if row.get("current_version") is not None else None)}


def _distinct(values) -> str:
    return ", ".join(dict.fromkeys(v for v in values if v))


def group_by_area(rows: list[dict]) -> list[dict]:
    """rule_catalog rows grouped for the page: one entry per area, in AREAS
    order, each with its code prefixes, owners and rules."""
    by_area: dict[str, list[dict]] = {}
    for r in rows:
        by_area.setdefault(r.get("area") or "unassigned", []).append(r)
    order = [a for a in AREAS if a in by_area] + sorted(set(by_area) - set(AREAS))
    return [{"area": AREAS.get(a, a), "key": a,
             "prefix": _distinct(r["rule_id"].split("-")[0] for r in by_area[a]),
             "owner_office": _distinct(r.get("owner_office") for r in by_area[a]),
             "owner_role": _distinct(r.get("owner_role") for r in by_area[a]),
             "rules": [_rule(r) for r in by_area[a]]}
            for a in order]


def gate_routes(gate: dict) -> list[dict]:
    """seed/gate.yaml routes, in the file's order, which is evaluation order."""
    return [{"code": code, "description": r["when"], "decision": r["decision"]}
            for code, r in (gate.get("routes") or {}).items()]


def register(q_app: QueryFn, snapshot: dict | None) -> dict:
    """The rule register, live. On failure, the snapshot, with the reason.
    The page always says which of the two it is showing."""
    try:
        rows = q_app(H.rule_catalog(H.tables()), {})
        error = None if rows else "The rule register returned no rows."
    except Exception as exc:  # noqa: BLE001 - shown on the page, not swallowed
        rows, error = [], str(exc)[:400]
    if error is None:
        return {"source": "live", "error": None, "built_at": None,
                "count": len(rows), "areas": group_by_area(rows)}
    snap = snapshot or {}
    areas = snap.get("areas") or []
    return {"source": "snapshot", "error": error, "built_at": snap.get("built_at"),
            "count": sum(len(a["rules"]) for a in areas), "areas": areas}


def page_context(q_app: QueryFn) -> dict:
    """Everything rules.html renders."""
    built = data.get("rules")      # generated by etl/build_rules.py
    return {"si_rules": si_rules(),
            "register": register(q_app, built.get("register_snapshot")),
            "gate_routes": built.get("gate_routes") or [],
            "built_at": built.get("built_at")}
